// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every
// other protocol below the floor that passes the watchlist's own rule: the early rows the radar
// exists to find. A protocol is pre-token when its index entry records no token (no market cap, no
// CoinGecko id, no symbol); the snapshot's live-token protocols are kept apart and shown as the
// market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, and its one free parameter is
// calibrated from the snapshot itself, never typed in:
//
//   base       = tvl_usd x BASE, where BASE is the median market-cap-to-TVL ratio of the
//                snapshot's own live-token protocols (clamped to [0.05, 1.00]). The market, not
//                the author, says what a dollar of TVL is worth as a token.
//   growth     = clamp(change_7d, -50, 100) per cent
//   growthMult = 1 + (growth / 100) x 0.6
//   maturity   = 0.65 + min(age_days, 1460) / 1460 x 0.35   (age_days unknown: 365)
//   chains     = 1 + 0.02 x min(chains - 1, 5)             (wider distribution, up to +10%)
//   implied    = max(1, round(base x growthMult x maturity x chains))
//
// No protocol name is ever special-cased: the same function scores every row, and the farm plan is
// derived from the protocol's own record (category, chains, TVL, age), never from a hand-written
// list of names.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

